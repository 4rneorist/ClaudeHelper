function subscribe<A extends unknown[]>(
  channel: string,
  listener: (...args: A) => void
): () => void {
  const wrapped = (_e: Electron.IpcRendererEvent, ...args: unknown[]): void =>
    listener(...(args as A))
  ipcRenderer.on(channel, wrapped)
  return () => ipcRenderer.removeListener(channel, wrapped)
}

